let n20 = null;

/**
 * A character's cell in the N?20WGL4 fonts: 12 x 20 pixels, a 1 for each
 * dark one, or null for a character this table does not have.
 */
export function n20Glyph(ch) {
  if (!n20) {
    n20 = new Map();
    for (const [key, data] of N20_GLYPH_DATA) {
      const bytes = atob(data);
      const bits = new Uint8Array(12 * 20);
      for (let i = 0; i < bits.length; i++) {
        bits[i] = (bytes.charCodeAt(i >> 3) >> (7 - (i & 7))) & 1;
      }
      n20.set(key, bits);
    }
  }
  return n20.get(ch) ?? null;
}
